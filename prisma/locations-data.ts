/** Şəhər/rayonun altındakı yaşayış məntəqəsi. */
export type ChildPlace = {
  name: string;
  kind: "SETTLEMENT" | "VILLAGE" | "NEIGHBORHOOD";
  /** Rəsmi kod (DSK / Ünvan Reyestri) — yalnız rəsmi məntəqədə. */
  code?: string;
};

/** Şəhərdaxili inzibati rayon — yalnız Bakı və Gəncədə var. */
export type UrbanDistrict = {
  name: string;
  code?: string;
  places: ChildPlace[];
};

/**
 * Birinci pillə: respublika tabeli şəhər və ya rayon.
 *
 * `tier` yalnız sıralama üçündür — bazada hər ikisi `kind="CITY"` olur, çünki
 * istifadəçi axtarışda onları eyni açılan siyahıdan seçir. Lənkəran, Şəki və
 * Yevlax rəsmi təsnifatda həm şəhər, həm eyniadlı rayondur; saytda tək qeyddir.
 */
export type TopLevelPlace = {
  name: string;
  tier: "CITY" | "REGION";
  code?: string;
  /** Şəhərdaxili inzibati rayonlar. */
  districts?: UrbanDistrict[];
  /** Birbaşa alt yaşayış məntəqələri. */
  places?: ChildPlace[];
};

